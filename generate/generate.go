// Package generate writes the Go client code for a schema.
package generate

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
	"text/template"

	"github.com/SanjayM-2002/prismo/schema"
)

var modelsTemplate = template.Must(template.New("models").Parse(`// Code generated by prismo. DO NOT EDIT.

package {{.Package}}
{{if .NeedsTime}}
import "time"
{{end}}
{{- range .Models}}
// {{.Name}} is a row in the {{.Table}} table.
type {{.Name}} struct {
{{- range .Fields}}
	{{.Name}} {{.Type}} ` + "`json:\"{{.JSON}}\"`" + `
{{- end}}
}
{{end}}`))

type modelsData struct {
	Package   string
	NeedsTime bool
	Models    []modelData
}

type modelData struct {
	Name   string
	Table  string
	Fields []fieldData
}

type fieldData struct {
	Name string
	Type string
	JSON string
}

// Models returns the Go source for one struct per model. The schema must
// already be validated.
func Models(s *schema.Schema, pkg string) ([]byte, error) {
	data := modelsData{Package: pkg}

	for _, m := range s.Models {
		md := modelData{Name: goName(m.Name), Table: m.Name}
		seen := map[string]string{}

		for _, f := range m.Fields {
			name := goName(f.Name)
			if other, ok := seen[name]; ok {
				return nil, fmt.Errorf("model %s: fields %s and %s both become Go field %s", m.Name, other, f.Name, name)
			}
			seen[name] = f.Name

			typ, err := goType(f)
			if err != nil {
				return nil, fmt.Errorf("model %s: %w", m.Name, err)
			}
			if f.Type == schema.DateTime {
				data.NeedsTime = true
			}
			md.Fields = append(md.Fields, fieldData{Name: name, Type: typ, JSON: f.Name})
		}
		data.Models = append(data.Models, md)
	}

	var buf bytes.Buffer
	if err := modelsTemplate.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("execute models template: %w", err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated models: %w", err)
	}
	return src, nil
}

func goType(f schema.Field) (string, error) {
	var typ string
	switch f.Type {
	case schema.Int:
		typ = "int"
	case schema.String:
		typ = "string"
	case schema.Boolean:
		typ = "bool"
	case schema.DateTime:
		typ = "time.Time"
	default:
		return "", fmt.Errorf("field %s: unsupported type %s", f.Name, f.Type)
	}
	if f.Optional {
		typ = "*" + typ
	}
	return typ, nil
}

var initialisms = map[string]bool{
	"API": true, "HTTP": true, "ID": true, "IP": true,
	"JSON": true, "SQL": true, "URL": true, "UUID": true,
}

// goName turns a schema name into an exported Go name, following Go's
// naming style: createdAt -> CreatedAt, user_id -> UserID.
func goName(s string) string {
	var b strings.Builder
	for _, w := range words(s) {
		if upper := strings.ToUpper(w); initialisms[upper] {
			b.WriteString(upper)
			continue
		}
		b.WriteString(strings.ToUpper(w[:1]) + w[1:])
	}
	return b.String()
}

// words splits a name at underscores and at lower-to-upper case changes:
// "user_createdAt" -> ["user", "created", "At"].
func words(s string) []string {
	var list []string
	for _, part := range strings.Split(s, "_") {
		start := 0
		for i := 1; i < len(part); i++ {
			if isUpper(part[i]) && !isUpper(part[i-1]) {
				list = append(list, part[start:i])
				start = i
			}
		}
		if start < len(part) {
			list = append(list, part[start:])
		}
	}
	return list
}

func isUpper(c byte) bool {
	return c >= 'A' && c <= 'Z'
}
