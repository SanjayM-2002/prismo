package generate

import (
	"bytes"
	"fmt"
	"go/format"
	"text/template"

	"github.com/SanjayM-2002/prismo/schema"
)

// Dialect tells the generator which dialect package the client uses at
// runtime. The package must have Open(ctx, url) (*sql.DB, error) and a
// Dialect type that satisfies query.Dialect.
type Dialect struct {
	// Import is the package's import path.
	Import string
	// Name is the package name used in the generated code.
	Name string
}

var clientTemplate = template.Must(template.New("client").Parse(`// Code generated by prismo. DO NOT EDIT.

package {{.Package}}

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
{{- if .URLEnv}}
	"os"
{{- end}}

	"{{.Dialect.Import}}"
)

// ErrNotFound is returned when no row matches a lookup.
var ErrNotFound = errors.New("not found")

// Client gives access to the queries for every model.
type Client struct {
	// db is nil for the client a transaction hands to its function.
	db *sql.DB
{{- range .Models}}
	{{.Name}} *{{.Name}}Client
{{- end}}
}

// executor runs queries: a *sql.DB, or a *sql.Tx inside Tx.
type executor interface {
	ExecContext(ctx context.Context, query string, args ...any) (sql.Result, error)
	QueryContext(ctx context.Context, query string, args ...any) (*sql.Rows, error)
	QueryRowContext(ctx context.Context, query string, args ...any) *sql.Row
}
{{if .URLEnv}}
// Open connects to the database in the {{.URLEnv}} environment variable.
func Open(ctx context.Context) (*Client, error) {
	url := os.Getenv({{printf "%q" .URLEnv}})
	if url == "" {
		return nil, errors.New({{printf "%q" (print "environment variable " .URLEnv " is not set")}})
	}
	db, err := {{.Dialect.Name}}.Open(ctx, url)
	if err != nil {
		return nil, err
	}
	return NewClient(db), nil
}
{{else}}
// Open connects to the database URL written in the schema.
func Open(ctx context.Context) (*Client, error) {
	db, err := {{.Dialect.Name}}.Open(ctx, {{printf "%q" .URL}})
	if err != nil {
		return nil, err
	}
	return NewClient(db), nil
}
{{end}}
// NewClient wraps a connection pool you already have. Open it with
// {{.Dialect.Name}}.Open so it has the settings the client needs.
func NewClient(db *sql.DB) *Client {
	c := newClient(db)
	c.db = db
	return c
}

func newClient(db executor) *Client {
	return &Client{
{{- range .Models}}
		{{.Name}}: &{{.Name}}Client{db: db},
{{- end}}
	}
}

// Close closes the connection pool.
func (c *Client) Close() error {
	if c.db == nil {
		return errors.New("close: can't close the client inside a transaction")
	}
	return c.db.Close()
}

// Tx runs fn in a transaction and commits it if fn returns nil. If fn
// returns an error or panics, everything fn did is rolled back. Run every
// query inside the transaction through the client fn receives.
func (c *Client) Tx(ctx context.Context, fn func(tx *Client) error) error {
	if c.db == nil {
		return errors.New("transaction: transactions can't be nested")
	}
	tx, err := c.db.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("begin transaction: %w", err)
	}
	// Rollback after a successful Commit does nothing, so this only undoes
	// the work when fn fails or panics.
	defer tx.Rollback()

	if err := fn(newClient(tx)); err != nil {
		return err
	}
	if err := tx.Commit(); err != nil {
		return fmt.Errorf("commit transaction: %w", err)
	}
	return nil
}

// Ptr returns a pointer to v, for setting optional fields: Name: Ptr("Sanjay").
func Ptr[T any](v T) *T {
	return &v
}
{{range .Models}}
// {{.Name}}Client runs queries on the {{.Table}} table.
type {{.Name}}Client struct {
	db executor
}
{{end}}`))

type clientData struct {
	Package string
	Dialect Dialect
	URLEnv  string
	URL     string
	Models  []modelData
}

// Client returns the Go source for the Client type, Open, NewClient and one
// query type per model. The schema must already be validated.
func Client(s *schema.Schema, pkg string, d Dialect) ([]byte, error) {
	if err := checkNames(s); err != nil {
		return nil, err
	}

	data := clientData{
		Package: pkg,
		Dialect: d,
		URLEnv:  s.Datasource.URLEnv,
		URL:     s.Datasource.URL,
	}
	for _, m := range s.Models {
		data.Models = append(data.Models, modelData{Name: goName(m.Name), Table: m.Name})
	}

	var buf bytes.Buffer
	if err := clientTemplate.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("execute client template: %w", err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated client: %w", err)
	}
	return src, nil
}
