type queriesData struct {
	Package   string
	Dialect   Dialect
	NeedsTime bool
	Models    []queryModel
}

type queryModel struct {
	Name  string
	Table string
	// Var is the prefix of the model's package-level variables: user -> userColumns.
	Var string
	// Columns is the Go list of column names: "id", "email".
	Columns string
	// Scan is the list of Scan targets in column order: &row.ID, &row.Email.
	Scan   string
	Unique []uniqueField
	// ID is the Go name of the @id field.
	ID string
	// AutoID is true when the database assigns the id (autoincrement()).
	AutoID bool
	Create []createField
	Where  []whereField
}

type whereField struct {
	Name   string
	Column string
	Type   string
}

type createField struct {
	Name    string
	Column  string
	Type    string
	Pointer bool
}

type uniqueField struct {
	Name   string
	Column string
	Param  string
	Type   string
}

// Queries returns the Go source for each model's query methods. The schema
// must already be validated.
func Queries(s *schema.Schema, pkg string, d Dialect) ([]byte, error) {
	if err := checkNames(s); err != nil {
		return nil, err
	}

	data := queriesData{Package: pkg, Dialect: d}

	for _, m := range s.Models {
		name := goName(m.Name)
		qm := queryModel{Name: name, Table: m.Name, Var: lowerName(name)}

		var columns, scan []string
		for _, f := range m.Fields {
			columns = append(columns, strconv.Quote(f.Name))
			scan = append(scan, "&row."+goName(f.Name))

			if f.ID {
				qm.ID = goName(f.Name)
				qm.AutoID = isAutoIncrement(f)
			}
			if !isAutoIncrement(f) {
				cf, err := createFieldFor(f)
				if err != nil {
					return nil, fmt.Errorf("model %s: %w", m.Name, err)
				}
				qm.Create = append(qm.Create, cf)
			}
			typ, err := goType(schema.Field{Name: f.Name, Type: f.Type})
			if err != nil {
				return nil, fmt.Errorf("model %s: %w", m.Name, err)
			}
			if f.Type == schema.DateTime {
				data.NeedsTime = true
			}

			qm.Where = append(qm.Where, whereField{Name: goName(f.Name), Column: f.Name, Type: "*" + typ})

			if !f.ID && !f.Unique {
				continue
			}
			// A lookup value is always given, so it's never a pointer.
			qm.Unique = append(qm.Unique, uniqueField{
				Name:   goName(f.Name),
				Column: f.Name,
				Param:  paramName(goName(f.Name)),
				Type:   typ,
			})
		}
		qm.Columns = strings.Join(columns, ", ")
		qm.Scan = strings.Join(scan, ", ")
		data.Models = append(data.Models, qm)
	}

	var buf bytes.Buffer
	if err := queriesTemplate.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("execute queries template: %w", err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated queries: %w", err)
	}
	return src, nil
}

func isAutoIncrement(f schema.Field) bool {
	return f.Default != nil && f.Default.Kind == schema.DefaultFunc && f.Default.Value == "autoincrement"
}

// createFieldFor returns the Create input field for f. Optional fields and
// fields with a default are pointers, so nil can mean "not given". The id is
// always required when the database doesn't assign it.
func createFieldFor(f schema.Field) (createField, error) {
	pointer := !f.ID && (f.Optional || f.Default != nil)
	typ, err := goType(schema.Field{Name: f.Name, Type: f.Type, Optional: pointer})
	if err != nil {
		return createField{}, err
	}
	return createField{Name: goName(f.Name), Column: f.Name, Type: typ, Pointer: pointer}, nil
}

// lowerName turns an exported Go name into an unexported one, keeping
// initialisms together: User -> user, URL -> url, HTTPServer -> httpServer.
func lowerName(name string) string {
	upper := 0
	for upper < len(name) && isUpper(name[upper]) {
		upper++
	}
	switch {
	case upper == len(name):
		return strings.ToLower(name)
	case upper > 1:
		// The last capital starts the next word: HTTPServer -> http + Server.
		upper--
	}
	return strings.ToLower(name[:upper]) + name[upper:]
}

// paramName returns a parameter name for a field that doesn't clash with
// Go keywords or the other names used in a generated method.
func paramName(goFieldName string) string {
	name := lowerName(goFieldName)
	if token.IsKeyword(name) || name == "c" || name == "ctx" || name == "query" {
		return name + "Value"
	}
	return name
}
